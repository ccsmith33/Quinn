# AC-4 — only 5 most recent retained
# ---------------------------------------------------------------------------


def test_only_5_most_recent_retained(
    checker: SimilarityChecker, db_path: str
) -> None:
    base = dt.datetime(2026, 1, 1, 9, 0, 0)
    for i in range(7):
        f = _filing(
            db_path=db_path,
            accession=f"0000001-26-{i:06d}",
            cik=320193,
            form_type="10-Q",
            filed_at=base + dt.timedelta(days=i * 30),
        )
        # Use distinct text so each is accepted (no MinHash/TF-IDF rejection).
        checker.check(f, _distinct_filing_text(i))

    cache = get_similarity_cache_for_issuer_form(db_path, 320193, "10-Q")
    assert len(cache) == 5

    retained_accessions = {row.accession_number for row in cache}
    expected = {f"0000001-26-{i:06d}" for i in range(2, 7)}  # last 5 = i=2..6
    assert retained_accessions == expected

    # Pruned files should be gone from disk.
    for i in range(2):
        for suffix in ("vectorizer.pkl", "vector.pkl", "text.txt"):
            stale = artifact_path_for(
                base_dir=checker.artifact_dir,
                cik=320193,
                form_type="10-Q",
                accession=f"0000001-26-{i:06d}",
                suffix=suffix,
            )
            assert not stale.exists(), f"stale {stale} still on disk"


def artifact_path_for(
    *, base_dir: str, cik: int, form_type: str, accession: str, suffix: str
) -> Path:
    """Mirror SimilarityChecker's on-disk layout for retention assertions."""
    safe_form = form_type.replace("/", "_").replace(" ", "_")
    return Path(base_dir) / str(cik) / safe_form / f"{accession}.{suffix}"


