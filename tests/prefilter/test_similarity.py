# AC-8 — p95 latency on synthetic corpus
# ---------------------------------------------------------------------------


def test_p95_latency_under_5s_on_synthetic_corpus(
    checker: SimilarityChecker, db_path: str
) -> None:
    """200 synthetic 10-K-sized filings; p95 of `check()` < 5s.

    Each iteration uses a unique CIK to exercise the worst-ish case (no MinHash
    short-circuit on prior; full TF-IDF fit/transform path). A real droplet
    would benchmark differently; the test rig target is conservative per the
    story note.
    """
    base = dt.datetime(2026, 1, 1, 9, 0, 0)
    paragraph = (
        "Risk factors. Investing in the company involves a high degree of risk. "
        "You should carefully consider the following risk factors before making an "
        "investment decision. Our business operations and financial results are "
        "subject to various risks and uncertainties including those described "
        "below which could adversely affect our business financial condition and "
        "results of operations. " * 200  # ~10K-token-ish body
    )
    n = 200
    durations: list[float] = []
    for i in range(n):
        f = _filing(
            db_path=db_path,
            accession=f"0000{i:03d}-26-000001",
            cik=900000 + i,  # unique CIK per iter
            form_type="10-K",
            filed_at=base + dt.timedelta(minutes=i),
        )
        text = f"Filing number {i} {paragraph}"
        t0 = time.perf_counter()
        checker.check(f, text)
        durations.append(time.perf_counter() - t0)

    durations.sort()
    p95 = durations[int(0.95 * n) - 1]
    assert p95 < 5.0, f"p95={p95:.3f}s exceeded 5s budget"
