def _filing(
    *,
    db_path: str,
    accession: str,
    cik: int,
    form_type: str,
    raw_text_path: str = "/tmp/unused.txt",
    filed_at: dt.datetime | None = None,
) -> FilingRow:
    """Persist a `filings` row and return it with `id` populated."""
    if filed_at is None:
        filed_at = dt.datetime(2026, 4, 1, 9, 0, 0)
    row = FilingRow(
        accession_number=accession,
        cik=cik,
        form_type=form_type,
        filed_at=filed_at,
        fetched_at=filed_at + dt.timedelta(seconds=30),
        raw_text_path=raw_text_path,
        content_hash="0" * 64,
    )
    new_id = insert_filing(db_path, row)
    return row.model_copy(update={"id": new_id})


def _ten_q_template(quarter_label: str, eps: float, revenue: float) -> str:
    """A 10-Q narrative with quarter-over-quarter near-identical language.

    The vast majority of the text is shared; only quarter label, EPS, and
    revenue numbers vary. This is the canonical "TF-IDF should catch but
    MinHash may miss" scenario from ADR-003.
    """
    boilerplate = (
        "Management's discussion and analysis of financial condition and results "
        "of operations. The following discussion should be read in conjunction with "
        "the unaudited condensed consolidated financial statements and notes thereto "
        "appearing elsewhere in this quarterly report. The discussion contains "
        "forward looking statements that involve risks and uncertainties. Our actual "
        "results may differ materially from those discussed in the forward looking "
        "statements as a result of various factors including those set forth under "
        "risk factors. We design develop and sell consumer electronics including "
        "mobile devices personal computers tablets wearables and accessories. Our "
        "products are sold through our retail and online stores and through "
        "third-party cellular network carriers wholesalers retailers and resellers. "
        "Critical accounting policies and estimates the preparation of consolidated "
        "financial statements in conformity with United States generally accepted "
        "accounting principles requires management to make estimates and assumptions "
        "that affect the reported amounts of assets and liabilities the disclosure of "
        "contingent assets and liabilities at the date of the financial statements and "
        "the reported amounts of revenues and expenses during the reporting periods. "
        "The Company believes its critical accounting policies and estimates are those "
        "related to revenue recognition inventory valuation income taxes and "
        "valuation and impairment of marketable securities. Liquidity and capital "
        "resources the Company believes that its balances of cash cash equivalents "
        "and marketable securities along with cash generated by ongoing operations "
        "and continued access to debt markets will be sufficient to satisfy its cash "
        "requirements and capital return program over the next twelve months and "
        "beyond. Recent accounting pronouncements in the current year the Company "
        "adopted the standard requiring lessees to recognize most leases on the "
        "balance sheet. The adoption did not have a material impact on the "
        "consolidated financial statements. " * 4
    )
    return (
        f"For the {quarter_label} quarter, diluted earnings per share were ${eps:.2f} "
        f"and total net sales were ${revenue:.2f} billion. {boilerplate}"
    )


def _distinct_filing_text(seed: int) -> str:
    """A substantively different filing — vocabulary varies with seed.

    Uses random-like word selection seeded by `seed` to ensure successive
    seeds produce texts whose lexical overlap stays well below the TF-IDF
    cosine threshold (0.97). This avoids accidental duplicate-rejection when
    the test wants the filing to be accepted.
    """
    import random

    rng = random.Random(seed)
    vocab = [
        "aerospace", "defense", "missile", "helicopter", "pharmaceutical",
        "oncology", "trial", "regulatory", "bank", "commercial", "real",
        "estate", "charge", "office", "capital", "dividend", "software",
        "platform", "retention", "margin", "headcount", "energy", "permian",
        "bakken", "production", "guidance", "manufacturing", "automotive",
        "supplier", "logistics", "warehouse", "freight", "rail", "container",
        "shipping", "consumer", "retail", "apparel", "footwear", "luxury",
        "jewelry", "biotechnology", "vaccine", "diagnostic", "device",
        "implant", "surgery", "hospital", "insurance", "underwriting",
        "actuarial", "claims", "premium", "reserve", "mortgage", "lending",
        "deposit", "checking", "savings", "credit", "card", "merchant",
        "processing", "payment", "wallet", "fintech", "blockchain", "token",
        "exchange", "brokerage", "advisory", "wealth", "trust", "endowment",
        "pension", "annuity", "longevity", "mortality", "morbidity", "claim",
        "subrogation", "reinsurance", "excess", "umbrella", "specialty",
        "marine", "aviation", "cyber", "ransomware", "phishing", "malware",
        "endpoint", "perimeter", "firewall", "intrusion", "incident",
    ]
    body_words = [rng.choice(vocab) for _ in range(800)]
    return f"Filing seed {seed}. " + " ".join(body_words)


# ---------------------------------------------------------------------------
# AC-5 — first filing for issuer/form accepts (records minhash)
# ---------------------------------------------------------------------------


def test_first_filing_for_issuer_form_accepted(
    checker: SimilarityChecker, db_path: str
) -> None:
    f = _filing(db_path=db_path, accession="0000001-26-000001", cik=320193, form_type="10-Q")
    text = _ten_q_template("first", 1.50, 90.00)

    decision = checker.check(f, text)

    assert isinstance(decision, SimilarityDecision)
    assert decision.decision == "accept"
    assert decision.reason == "pass"
    assert decision.score is None

    cache = get_similarity_cache_for_issuer_form(db_path, 320193, "10-Q")
    assert len(cache) == 1
    assert cache[0].accession_number == f.accession_number
    assert cache[0].minhash_blob  # non-empty


# ---------------------------------------------------------------------------
# AC-2 — identical text re-filing rejects via MinHash
# ---------------------------------------------------------------------------


def test_identical_re_filing_minhash_rejects(
    checker: SimilarityChecker, db_path: str
) -> None:
    text = _ten_q_template("Q1", 1.50, 90.00)

    f1 = _filing(
        db_path=db_path,
        accession="0000001-26-000001",
        cik=320193,
        form_type="10-Q",
        filed_at=dt.datetime(2026, 1, 30, 9, 0, 0),
    )
    assert checker.check(f1, text).decision == "accept"

    # Same issuer, same form, identical text re-filed two days later.
    f2 = _filing(
        db_path=db_path,
        accession="0000001-26-000002",
        cik=320193,
        form_type="10-Q",
        filed_at=dt.datetime(2026, 2, 1, 9, 0, 0),
    )
    decision = checker.check(f2, text)

    assert decision.decision == "reject"
    assert decision.reason == "minhash"
    assert decision.score is not None and decision.score >= 0.99


# ---------------------------------------------------------------------------
# AC-3 — near-identical 10-Q rejects via TF-IDF cosine
# ---------------------------------------------------------------------------


def test_near_identical_10q_tfidf_rejects(
    checker: SimilarityChecker, db_path: str
) -> None:
    """Quarter-over-quarter narrative: tiny numeric diffs, vast shared boilerplate.

    This is the ADR-003 scenario where MinHash on 5-word shingles MAY estimate
    Jaccard < 0.99 (because the shingles spanning the differing tokens differ),
    but TF-IDF cosine on 1-2 word n-grams with stopword removal stays >= 0.97.
    """
    f1 = _filing(
        db_path=db_path,
        accession="0000001-26-000001",
        cik=320193,
        form_type="10-Q",
        filed_at=dt.datetime(2026, 1, 30, 9, 0, 0),
    )
    text_q1 = _ten_q_template("first", 1.50, 90.00)
    assert checker.check(f1, text_q1).decision == "accept"

    f2 = _filing(
        db_path=db_path,
        accession="0000001-26-000002",
        cik=320193,
        form_type="10-Q",
        filed_at=dt.datetime(2026, 4, 30, 9, 0, 0),
    )
    text_q2 = _ten_q_template("second", 1.55, 92.00)

    decision = checker.check(f2, text_q2)

    # We expect rejection. If MinHash catches it, that's fine; the spec lets either
    # stage fire. But the specific intent of this case is the TF-IDF path.
    assert decision.decision == "reject"
    assert decision.reason in {"minhash", "tfidf_cosine"}
    assert decision.score is not None and decision.score >= 0.97


