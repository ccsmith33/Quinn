"""S4.2 — Similarity prefilter tests (ADR-003).

Two-stage check on normalized plaintext:
  Stage 1 — 128-perm MinHash on 5-word shingles (>=0.99 → reject)
  Stage 2 — per-(cik, form_type) TF-IDF cosine (>=threshold → reject)

Form 4 is excluded from similarity (universe-only per PRD §8.3 / D-014).
"""

