# AC-4 — vectorizer persistence (load survives restart)
# ---------------------------------------------------------------------------


def test_vectorizer_persisted_and_loaded(
    db_path: str, artifact_dir: Path
) -> None:
    chk1 = SimilarityChecker(
        db_path=db_path, artifact_dir=str(artifact_dir), threshold=0.97
    )
    f1 = _filing(
        db_path=db_path,
        accession="0000001-26-000001",
        cik=320193,
        form_type="10-Q",
        filed_at=dt.datetime(2026, 1, 30, 9, 0, 0),
    )
    chk1.check(f1, _ten_q_template("Q1", 1.50, 90.00))

    cache = get_similarity_cache_for_issuer_form(db_path, 320193, "10-Q")
    assert len(cache) == 1
    assert Path(cache[0].tfidf_vectorizer_path).is_file()
    assert Path(cache[0].tfidf_vector_path).is_file()

    # Fresh checker (simulating process restart) loads existing artifacts.
    chk2 = SimilarityChecker(
        db_path=db_path, artifact_dir=str(artifact_dir), threshold=0.97
    )
    f2 = _filing(
        db_path=db_path,
        accession="0000001-26-000002",
        cik=320193,
        form_type="10-Q",
        filed_at=dt.datetime(2026, 4, 30, 9, 0, 0),
    )
    decision = chk2.check(f2, _ten_q_template("Q1", 1.50, 90.00))
    assert decision.decision == "reject"
    assert decision.reason == "minhash"


